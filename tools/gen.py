#!/usr/bin/env python3
"""Regenerate src/ from Emulator.x and the files in annotations/.

The generator never invents code: every instruction it writes is decoded
from the reference image, and the result is only trusted once `make verify`
has reassembled it and compared it with the original.  Annotation files
contribute names and prose only.

Inputs
    Emulator.x                      reference image (XCOFF)
    src/include/Registers.inc       register role names, CR flag names
    src/include/EmulatorState.inc   EmulatorState field names
    annotations/layout.txt          which source file each range goes to
    annotations/hints.txt           data ranges and other per-address hints
    annotations/*.ann               labels, block comments, line comments

Outputs
    src/Emulator.S and every file named in layout.txt
"""

import collections
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import drmap    # noqa: E402
import m68k     # noqa: E402
import naming   # noqa: E402
import ppc      # noqa: E402
import ppcsim   # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

XCOFF_HEADER_SIZE = 0x3C
IMAGE_SIZE = 0xA0000
TABLE_START = 0x20000           # OpcodeTblTop
CODE_BLOCK = 0x10000            # size of the block addressed through code_ptr

MNEM_COL = 8                    # column where the mnemonic starts
OPND_COL = 16                   # column where operands start
COMMENT_COL = 56                # preferred column for end-of-line comments

# Labels that share an offset with another label: the XCOFF symbols (EmEntry
# and EmKernelTrapTable are ordinary labels supplied by the annotations) and
# dr_cb, the base of the dynamic recompiler's 64 KB code block.
EXTRA_LABELS = {0x00000: ['EmTop'], 0x10000: ['dr_cb'],
                TABLE_START: ['EmBtm', 'OpcodeTblTop']}

AUTO_LABEL = re.compile(r'[LDT]_[0-9A-F]{5}|.*_L[0-9]+')
PASS3_END = 0x1782C              # end of the recompiler's emitters and their helpers
LOCAL_LABEL_REACH = 0x200        # bytes; see Generator.name_local_labels

GENERATED_BANNER = (
    '// Generated by tools/gen.py from Emulator.x and annotations/ - do not edit.\n'
    '// To change a name or a comment edit annotations/ and run "make regen".\n')


def fail(message):
    sys.exit('gen.py: ' + message)


# ---------------------------------------------------------------------------
# Input parsing
# ---------------------------------------------------------------------------

def read_lines(path):
    with open(path, encoding='utf-8') as handle:
        return handle.read().split('\n')


def parse_defines(path):
    """Return {section: [(name, value, comment)]} for an include file whose
    sections are introduced by `//@ name` marker lines."""
    sections = collections.OrderedDict()
    current = None
    pattern = re.compile(r'#define\s+(\w+)\s+(0[xX][0-9A-Fa-f]+|\d+)\s*(?://\s*(.*))?$')
    for line in read_lines(path):
        marker = re.match(r'//@\s*(\w+)', line)
        if marker:
            current = marker.group(1)
            sections.setdefault(current, [])
            continue
        match = pattern.match(line.strip())
        if match and current:
            sections[current].append(
                (match.group(1), int(match.group(2), 0), match.group(3) or ''))
    return sections


class Annotations:
    """Everything a human has told the generator about the image."""

    def __init__(self, directory):
        self.labels = {}                        # addr -> name
        self.blocks = {}                        # addr -> [comment lines]
        self.eols = {}                          # addr -> comment
        self.data = []                          # (start, end, kind)
        self.aligns = {}                        # addr -> alignment
        self.reg_overrides = []                 # (start, end, regno, name)
        self.operands = {}                      # addr -> replacement operand text
        self.layout = []                        # (start, path, kind)
        self.frozen = set()                     # files that are now maintained by hand
        self._load_layout(os.path.join(directory, 'layout.txt'))
        self._load_hints(os.path.join(directory, 'hints.txt'))
        for name in sorted(os.listdir(directory)):
            if name.endswith('.ann'):
                self._load_ann(os.path.join(directory, name))

    @staticmethod
    def _meaningful(path):
        for number, line in enumerate(read_lines(path), 1):
            text = line.split('#', 1)[0].rstrip()
            if text.strip():
                yield number, text

    def _load_layout(self, path):
        for number, text in self._meaningful(path):
            fields = text.split()
            if len(fields) not in (3, 4) or fields[3:] not in ([], ['frozen']):
                fail('%s:%d: expected "start file kind [frozen]"' % (path, number))
            self.layout.append((int(fields[0], 16), fields[1], fields[2]))
            if fields[3:]:
                self.frozen.add(fields[1])
        self.layout.sort()
        if not self.layout or self.layout[0][0] != 0:
            fail('layout must start at offset 0')

    def _load_hints(self, path):
        for number, text in self._meaningful(path):
            fields = text.split()
            kind = fields[0]
            try:
                if kind == 'data':
                    self.data.append((int(fields[1], 16), int(fields[2], 16), fields[3]))
                elif kind == 'align':
                    self.aligns[int(fields[1], 16)] = int(fields[2], 0)
                elif kind == 'reg':
                    self.reg_overrides.append(
                        (int(fields[1], 16), int(fields[2], 16),
                         int(fields[3].lstrip('r')), fields[4]))
                elif kind == 'opnd':
                    self.operands[int(fields[1], 16)] = text.split(None, 2)[2]
                else:
                    raise ValueError(kind)
            except (IndexError, ValueError):
                fail('%s:%d: bad hint: %s' % (path, number, text))
        self.data.sort()

    def _load_ann(self, path):
        """Parse an annotation file.

            @0C410 optional_label
                Block comment text, indented, placed above offset 0C410.
                A line holding only "." gives an empty comment line.
            0C414  end-of-line comment for the instruction at 0C414
        """
        current = None
        for number, line in enumerate(read_lines(path), 1):
            if not line.strip() or line.startswith('#'):
                continue
            header = re.match(r'@([0-9A-Fa-f]{5})(?:\s+([A-Za-z_][\w.]*))?\s*$', line)
            if header:
                current = int(header.group(1), 16)
                if header.group(2):
                    if current in self.labels:
                        fail('%s:%d: offset %05X already has label %s'
                             % (path, number, current, self.labels[current]))
                    self.labels[current] = header.group(2)
                continue
            if line[0] in ' \t':
                if current is None:
                    fail('%s:%d: comment text before any @ header' % (path, number))
                text = line.strip()
                self.blocks.setdefault(current, []).append('' if text == '.' else text)
                continue
            eol = re.match(r'([0-9A-Fa-f]{5})\s+(.*\S)\s*$', line)
            if eol:
                self.eols[int(eol.group(1), 16)] = eol.group(2)
                continue
            fail('%s:%d: cannot parse: %s' % (path, number, line))


