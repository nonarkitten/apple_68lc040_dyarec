class Generator:
    def __init__(self):
        with open(os.path.join(ROOT, 'Emulator.x'), 'rb') as handle:
            blob = handle.read()
        self.image = blob[XCOFF_HEADER_SIZE:XCOFF_HEADER_SIZE + IMAGE_SIZE]
        if len(self.image) != IMAGE_SIZE:
            fail('Emulator.x is shorter than expected')
        self.words = struct.unpack('>%dI' % (IMAGE_SIZE // 4), self.image)

        regs = parse_defines(os.path.join(ROOT, 'src/include/Registers.inc'))
        self.gpr = ['r%d' % n for n in range(32)]
        for name, value, _ in regs.get('gpr', []):
            self.gpr[value] = name
        self.crbit = {value: name for name, value, _ in regs.get('crbit', [])}
        state = parse_defines(os.path.join(ROOT, 'src/include/EmulatorState.inc'))
        self.state = {value: name for name, value, _ in state.get('state', [])}

        self.ann = Annotations(os.path.join(ROOT, 'annotations'))
        self.flag_bits = frozenset(self.crbit)

        self.kind = {}          # word-aligned addr -> ('insn', Insn) | ('data', kind)
        self.data_at = {}       # addr -> (start, end, kind) for every byte range start
        self.labels = dict(self.ann.labels)
        self.label_addrs = {}
        self.table_users = collections.defaultdict(list)    # handler -> [opcode]
        self.continuation_users = collections.defaultdict(list)
        self.emitter_users = collections.defaultdict(list)  # emitter -> [opcode]
        self.decoder_users = {}                             # pass-1 decoder helper -> [opcode]
        self.emitter_examples = {}                          # emitter -> comment lines
        self.emitter_refs = {}  # addr of "li out_ptr, n" -> emitter address
        self.code_refs = {}     # addr of an "ori x, code_ptr, imm" -> referenced offset
        self.template_refs = {} # addr of an "lwz/addi x, n(base_disp)" in an emitter -> dr_emitters + n
        self.templates = set()  # addresses of words that emitters load as instruction templates
        self.branch_refs = collections.defaultdict(list)    # target -> addresses of branches to it

    # -- analysis ----------------------------------------------------------

    def in_data(self, addr):
        for start, end, kind in self.ann.data:
            if start <= addr < end:
                return (start, end, kind)
        return None

    def analyse(self):
        data_words = {}
        for start, end, kind in self.ann.data:
            for addr in range(start & ~3, end, 4):
                data_words[addr] = (start, end, kind)
            self.data_at[start] = (start, end, kind)

        for index, word in enumerate(self.words):
            addr = index * 4
            if addr in data_words:
                self.kind[addr] = ('data', data_words[addr])
                continue
            insn = ppc.decode(word, addr, self.flag_bits)
            if insn is not None:
                for operand in insn.ops:
                    if operand[0] == 'tgt':
                        target = operand[1]
                        if target >= IMAGE_SIZE or target & 3 or target in data_words:
                            insn = None
            self.kind[addr] = ('insn', insn) if insn else ('long', word)

        # Collect everything that needs a label.
        wanted = set()
        for addr, (kind, value) in self.kind.items():
            if kind != 'insn':
                continue
            for operand in value.ops:
                if operand[0] == 'tgt':
                    wanted.add(operand[1])
                    self.branch_refs[operand[1]].append(addr)
            if (value.mnem == 'ori' and value.ops[1] == ('r', 30)
                    and value.ops[0] != ('r', 30)):
                ref = value.ops[2][1]
                if ref & 3 == 0 or ref in self.data_at or ref in self.labels:
                    self.code_refs[addr] = ref
                    wanted.add(ref)

        # 16-bit code offset tables refer to labels too.
        for start, end, kind in self.ann.data:
            if kind in ('offs16', 'offs16e'):
                base = drmap.DR_EMITTERS if kind == 'offs16e' else 0
                for addr in range(start, end, 2):
                    value = struct.unpack('>H', self.image[addr:addr + 2])[0]
                    if value:
                        wanted.add(base + value)
            if kind in ('seq8', 'seq16'):
                # The recompiler's condition tables: each long word names a
                # run of templates by the offset from dr_emitters of the
                # word before it, and gives the number of templates plus one
                # (seq8: in one byte, followed by a byte of flags).
                for addr in range(start, end, 4):
                    offset, rest = struct.unpack('>HH', self.image[addr:addr + 4])
                    count = (rest >> 8 if kind == 'seq8' else rest) - 1
                    if offset:
                        first = drmap.DR_EMITTERS + offset + 4
                        wanted.add(first)
                        self.templates.update(range(first, first + 4 * count, 4))
            wanted.add(start)

        # Which 68K opcodes reach each routine, and how.
        direct = collections.defaultdict(list)          # second instruction: b handler
        ea_users = collections.defaultdict(list)        # ... with rtn_addr loaded
        for opcode in range(0x10000):
            entry = TABLE_START + opcode * 8
            continuation = self.code_refs.get(entry)
            if continuation is not None and self.kind[entry][1].ops[0] != ('r', 5):
                continuation = None
            if continuation is not None:
                self.continuation_users[continuation].append(opcode)
            for addr in (entry, entry + 4):
                kind, value = self.kind[addr]
                if kind != 'insn':
                    continue
                for operand in value.ops:
                    if operand[0] == 'tgt':
                        self.table_users[operand[1]].append(opcode)
                        if addr == entry + 4 and operand[1] < TABLE_START:
                            direct[operand[1]].append(opcode)
                            if continuation is not None:
                                ea_users[operand[1]].append(opcode)

        automatic = naming.assign(self, direct, self.continuation_users, ea_users)

        # The recompiler's code generators, from its own pass-1 decoder.
        decisions = drmap.scan(self.image[:TABLE_START],
                               cache=os.path.join(ROOT, 'build', 'drmap.json'))
        for opcode, decision in decisions.items():
            if decision.translated:
                self.emitter_users[drmap.DR_EMITTERS + decision.emitter].append(opcode)
        for addr in self.emitter_users:
            if not 0 <= addr < TABLE_START or self.kind[addr & ~3][0] != 'insn' or addr & 3:
                fail('emitter offset %05X is not code' % addr)
        automatic.update(naming.emitter_names(self.emitter_users))
        # The helpers of the pass-1 decoders, from the opcodes that pass
        # through them.
        for addr, opcodes in drmap.paths(self.image[:TABLE_START], cache=os.path.join(
                ROOT, 'build', 'drpaths.json')).items():
            if drmap.DR_LINE_0 <= addr < drmap.DR_EMITTERS and self.kind[addr][0] == 'insn':
                self.decoder_users[addr] = opcodes
        automatic.update(naming.decoder_names(self.decoder_users, drmap.DR_LINE_0))
        # "li out_ptr, n" in the pass-1 decoders selects emitter n.
        offsets = {addr - drmap.DR_EMITTERS: addr for addr in self.emitter_users}
        for addr in range(drmap.DR_LINE_0, drmap.DR_EMITTERS, 4):
            kind, value = self.kind[addr]
            if (kind == 'insn' and value.mnem == 'li' and value.ops[0] == ('r', 30)
                    and value.ops[1][1] in offsets):
                self.emitter_refs[addr] = offsets[value.ops[1][1]]

        # While the emitters run (pass 3), base_disp holds dr_emitters.
        # "lwz x, n(base_disp)" loads a template - an instruction word to be
        # copied into the translation - and "addi x, base_disp, n" forms the
        # address of a table.
        for addr in range(drmap.DR_EMITTERS, PASS3_END, 4):
            kind, value = self.kind[addr]
            if kind != 'insn':
                continue
            offset = None
            if value.mnem == 'lwz' and value.ops[1][0] == 'mem' and value.ops[1][2][1] == 7:
                offset = value.ops[1][1]
            elif value.mnem == 'addi' and value.ops[1] == ('r', 7) and value.ops[0] != ('r', 7):
                offset = value.ops[2][1]
            if offset is None or offset & 3:
                continue
            target = drmap.DR_EMITTERS + offset
            if drmap.DR_EMITTERS <= target < PASS3_END:
                self.template_refs[addr] = target
                wanted.add(target)
                if value.mnem == 'lwz' and self.kind[target][0] != 'data':
                    self.templates.add(target)

        # The recompiler's operand emitters are reached through tables of
        # offsets from dr_emitters, indexed by a 6-bit effective address
        # field.  A table labelled x_table names its routines x_<mode><reg>.
        for start, end, kind in self.ann.data:
            table = self.labels.get(start, '')
            if kind == 'offs16e' and table.endswith('_table'):
                for addr in range(start, end, 2):
                    value = struct.unpack('>H', self.image[addr:addr + 2])[0]
                    field = (addr - start) // 2
                    if value:
                        automatic.setdefault(drmap.DR_EMITTERS + value, '%s_%d%d' % (
                            table[:-len('_table')], field >> 3, field & 7))

        taken = set(self.labels.values())
        for addr, name in automatic.items():
            if addr not in self.labels:
                while name in taken:
                    name += '_'
                self.labels[addr] = name
                taken.add(name)

        for addr in sorted(wanted):
            if addr not in self.labels:
                self.labels[addr] = self.auto_label(addr)
        self.name_local_labels()
        seen = {}
        for addr, name in self.labels.items():
            if name in seen:
                fail('label %s used for both %05X and %05X' % (name, seen[name], addr))
            seen[name] = addr
        self.label_addrs = seen
        self.make_emitter_examples(decisions)

    def make_emitter_examples(self, decisions):
        """For each of the recompiler's code generators, run the translator
        (in the simulator) on one instruction that uses it, and keep what
        it generated as comment lines: once with every condition code wanted
        afterwards and once with none."""
        import check
        import drtranslate
        tail = 5                # an RTS after the sample: lwz, addi, bl and two data words
        dead = [0xD482]         # ADD.L D2,D2 replaces all five flags; two instructions

        def generated(words, drop):
            try:
                m, start, end = drtranslate.translate(self, words)
            except (RuntimeError, KeyError, ppcsim.Unimplemented, ppcsim.Limit):
                return None
            lines = drtranslate.render(self, m, start, end)
            if drop:
                lines = lines[lines.index('entry:') + 1:len(lines) - drop]
                return ['//         ' + ' '.join(line.split()[1:2]).ljust(7) + ' '
                        + ' '.join(line.split()[2:]) for line in lines]
            return ['//     ' + line.rstrip() for line in lines if '.long   0x00000000' not in line]

        def simplicity(opcode):
            op = m68k.decode(opcode)
            memory = sum(1 for operand in (op.src, op.dst) if operand and '(' in operand)
            return (not op.legal, bool(check.known_recompiler_defect(opcode)),
                    check.extension_words(op)[0], memory, opcode)

        for addr, users in self.emitter_users.items():
            opcode = min(users, key=simplicity)
            op = m68k.decode(opcode)
            words = [opcode] + [0x0010] * check.extension_words(op)[0]
            title = '// For %s, %s, it generates' % (
                ' '.join('%04X' % word for word in words), ' '.join(m68k.text(op).split()))
            if decisions[opcode].ends_block:
                whole = generated(words, 0)
                if whole:
                    self.emitter_examples[addr] = [title + ' the block'] + whole
                continue
            if decisions[opcode].flags & drmap.FLAG_CONTROL_TRANSFER:
                whole = generated(words + [0x4E71, 0x4E75], 0)
                if whole:
                    self.emitter_examples[addr] = [
                        title.replace(', it generates', ' (then NOP and RTS), it generates')
                        + ' the block'] + whole
                continue
            wanted = generated(words + [0x4E75], tail)
            unwanted = generated(words + dead + [0x4E75], tail + 2)
            if wanted is None or unwanted is None:
                continue
            lines = [title] + (wanted or ['//         (nothing)'])
            if unwanted != wanted:
                lines += ['// and, when the condition codes are not wanted afterwards,']
                lines += unwanted or ['//         (nothing)']
            self.emitter_examples[addr] = lines

    def name_local_labels(self):
        """Give branch targets that have no name of their own a name relative
        to the routine they follow: <routine>_L1, <routine>_L2, ...  A target
        further than LOCAL_LABEL_REACH from the nearest named label keeps
        its address-style name, since "local to that routine" would then be
        a guess - unless every branch to it comes from between that named
        label and the next one, which settles it."""
        code = sorted(addr for addr in self.labels if addr < TABLE_START)
        named = [addr for addr in code if not AUTO_LABEL.fullmatch(self.labels[addr])]
        anchor, count, limit = None, 0, 0
        for addr in code:
            name = self.labels[addr]
            if not AUTO_LABEL.fullmatch(name):
                anchor, count = addr, 0
                following = [other for other in named if other > addr]
                limit = following[0] if following else TABLE_START
                continue
            if (name.startswith('L_') and anchor is not None
                    and (addr - anchor <= LOCAL_LABEL_REACH
                         or (self.branch_refs[addr]
                             and all(anchor <= ref < limit for ref in self.branch_refs[addr])))
                    and (addr < CODE_BLOCK) == (anchor < CODE_BLOCK)):
                count += 1
                self.labels[addr] = '%s_L%d' % (self.labels[anchor], count)

    def auto_label(self, addr):
        if addr >= TABLE_START:
            opcode, second = divmod(addr - TABLE_START, 8)
            return 'op_%04X' % opcode + ('_2' if second else '')
        if addr in self.data_at:
            return 'D_%05X' % addr
        if addr in self.templates:
            return 'T_%05X' % addr
        return 'L_%05X' % addr

    # -- operand formatting ------------------------------------------------

    def reg(self, number, addr):
        for start, end, regno, name in self.ann.reg_overrides:
            if regno == number and start <= addr < end:
                return name
        return self.gpr[number]

    def crbit_name(self, bit):
        if bit in self.crbit:
            return self.crbit[bit]
        field, cond = bit >> 2, ('lt', 'gt', 'eq', 'so')[bit & 3]
        return cond if field == 0 else '4*cr%d+%s' % (field, cond)

    def crbit_prose(self, bit):
        if bit in self.crbit:
            return self.crbit[bit]
        return 'cr%d.%s' % (bit >> 2, ('lt', 'gt', 'eq', 'so')[bit & 3])

    @staticmethod
    def number(value):
        if -256 < value < 256:
            return str(value)
        return '-0x%X' % -value if value < 0 else '0x%X' % value

    def operand(self, operand, addr, insn):
        kind = operand[0]
        if kind == 'r':
            return self.reg(operand[1], addr)
        if kind == 'rz':
            return '0' if operand[1] == 0 else self.reg(operand[1], addr)
        if kind == 'crf':
            return 'cr%d' % operand[1]
        if kind == 'crb':
            return self.crbit_name(operand[1])
        if kind == 'simm':
            return self.number(operand[1])
        if kind == 'uimm':
            return '0x%04X' % operand[1]
        if kind == 'n':
            if insn.mnem == 'mtcrf':
                return '0x%02X' % operand[1]
            return str(operand[1])
        if kind == 'mem':
            disp, base = operand[1], operand[2]
            base_text = self.operand(base, addr, insn)
            if base == ('r', 31) or base == ('rz', 31):
                if disp in self.state and self.reg(31, addr) == self.gpr[31]:
                    return '%s(%s)' % (self.state[disp], base_text)
            return '%s(%s)' % (self.number(disp), base_text)
        if kind == 'tgt':
            return self.labels[operand[1]]
        raise ValueError(operand)

    def instruction_text(self, addr, insn):
        operands = [self.operand(o, addr, insn) for o in insn.ops]
        if addr in self.code_refs:
            operands[2] = '%s - cb' % self.labels[self.code_refs[addr]]
        if addr in self.emitter_refs:
            operands[1] = '%s - dr_emitters' % self.labels[self.emitter_refs[addr]]
        if addr in self.template_refs:
            label = self.labels[self.template_refs[addr]]
            if insn.mnem == 'lwz':
                operands[1] = '%s - dr_emitters(%s)' % (label, self.reg(7, addr))
            else:
                operands[2] = '%s - dr_emitters' % label
        if addr in self.ann.operands:
            operands[-1] = self.ann.operands[addr]
        text = ' ' * MNEM_COL + insn.mnem
        if operands:
            text = text.ljust(OPND_COL - 1) + ' ' + ', '.join(operands)
        return text

    # -- automatic comments ------------------------------------------------

    def idiom_comment(self, addr, insn):
        """Comments for the handful of instruction patterns that make up the
        emulator's fetch/decode/dispatch sequence and its flag handling.
        The capitalised names are the macro names used in US5574873."""
        m, ops = insn.mnem, insn.ops
        R = lambda n: ('r', n)
        if self.reg(27, addr) != self.gpr[27] or self.reg(29, addr) != self.gpr[29]:
            return None
        if m == 'lhau' and ops[1][2] == R(24):
            what = 'PREFETCH' if ops[0] == R(27) else '%s = next word' % self.reg(ops[0][1], addr)
            if ops[1][1] == 2:
                return what + ': pc += 2, load the word there'
            if ops[1][1] == 4:
                return what + ': pc += 4, load the word there'
        if m == 'rlwimi' and ops[0] == R(29) and (ops[2][1], ops[3][1], ops[4][1]) == (3, 13, 28):
            return 'DECODE1: disp_table[18:3] = opcode in %s' % self.reg(ops[1][1], addr)
        if m in ('mtlr', 'mtctr') and ops[0] == R(29):
            return 'DECODE2: %s = address of the next dispatch entry' % m[2:].upper()
        if m in ('bflr_likely', 'bfctr_likely') and ops[0] == ('crb', 8):
            return 'DISPATCH unless a special event is pending'
        if m in ('addco.', 'addco') and ops[2] == R(0):
            dot = m.endswith('.')
            dst, src = ops[0], ops[1]
            if src == R(0):
                if dst == R(0):
                    return 'N=0, Z=1, V=0, C=0' if dot else 'V=0, C=0'
                if dst == R(26) and dot:
                    return 'N=0, Z=1, V=0, C=0, X=0'
            flags = 'N,Z from result; V=0, C=0' if dot else 'V=0, C=0'
            if dst == src:
                return ('test %s: ' % self.reg(dst[1], addr)) + flags
            return '%s = %s; %s' % (self.reg(dst[1], addr), self.reg(src[1], addr), flags)
        if m == 'mfxer' and ops[0] == R(26):
            return 'X = C (ccr_x keeps a copy of XER)'
        return None


    def auto_comment(self, addr, insn):
        """Explain instructions whose effect is not obvious from the mnemonic."""
        m = insn.mnem.rstrip('.')
        ops = insn.ops
        name = lambda i: self.operand(ops[i], addr, insn)

        if addr in self.template_refs and insn.mnem == 'lwz':
            kind, value = self.kind[self.template_refs[addr]]
            if kind == 'insn':
                return 'template: ' + ' '.join(self.instruction_text(
                    self.template_refs[addr], value).split())
            if kind == 'long':
                return 'template: 0x%08X' % value
        if addr in self.templates:
            return 'template'

        idiom = self.idiom_comment(addr, insn)
        if idiom:
            return idiom

        if m in ('rlwinm', 'rlwimi'):
            sh, mb, me = ops[2][1], ops[3][1], ops[4][1]
            mask = mask32(mb, me)
            if mb <= me:
                hi, lo = 31 - mb, 31 - me
                src_lo, src_hi = (lo - sh) % 32, (hi - sh) % 32
                if src_lo <= src_hi:
                    source = name(1) + bit_slice(src_hi, src_lo)
                    if m == 'rlwimi':
                        return '%s%s = %s' % (name(0), bit_slice(hi, lo), source)
                    if lo:
                        return '%s = %s << %d' % (name(0), source, lo)
                    return '%s = %s' % (name(0), source)
            rotated = 'rotl(%s, %d)' % (name(1), sh) if sh else name(1)
            if m == 'rlwimi':
                return '%s = (%s & ~0x%08X) | (%s & 0x%08X)' % (
                    name(0), name(0), mask, rotated, mask)
            return '%s = %s & 0x%08X' % (name(0), rotated, mask)
        if m == 'rlwnm':
            mask = mask32(ops[3][1], ops[4][1])
            return '%s = rotl(%s, %s) & 0x%08X' % (name(0), name(1), name(2), mask)
        if m == 'clrlwi':
            return '%s = %s & 0x%08X' % (name(0), name(1), mask32(ops[2][1], 31))
        if m == 'clrrwi':
            return '%s = %s & 0x%08X' % (name(0), name(1), mask32(0, 31 - ops[2][1]))
        if m == 'rotlwi':
            if ops[2][1] == 16:
                return '%s = %s with halves swapped' % (name(0), name(1))
            return '%s = rotl(%s, %d)' % (name(0), name(1), ops[2][1])
        if m == 'srawi':
            return '%s = %s >> %d (arithmetic)' % (name(0), name(1), ops[2][1])
        if m == 'sraw':
            return '%s = %s >> %s (arithmetic)' % (name(0), name(1), name(2))

        if m == 'mtcrf':
            mask = ops[0][1]
            fields = [f for f in range(8) if mask & (0x80 >> f)]
            parts = []
            for field in fields:
                parts.append('cr%d = %s%s' % (
                    field, name(1), bit_slice(31 - 4 * field, 28 - 4 * field)))
            if len(fields) > 1 and fields == list(range(fields[0], fields[-1] + 1)):
                return 'cr%d..cr%d = %s%s' % (
                    fields[0], fields[-1], name(1),
                    bit_slice(31 - 4 * fields[0], 28 - 4 * fields[-1]))
            return '; '.join(parts)
        if m == 'mtcr':
            return 'CR = %s' % name(0)
        if m == 'mcrf':
            return 'cr%d = cr%d' % (ops[0][1], ops[1][1])
        if m == 'mcrxr':
            return 'cr%d = XER[SO,OV,CA]; clear them in XER' % ops[0][1]

        cr_logic = {'crand': '%s & %s', 'cror': '%s | %s', 'crxor': '%s ^ %s',
                    'crnand': '~(%s & %s)', 'crnor': '~(%s | %s)',
                    'creqv': '~(%s ^ %s)', 'crandc': '%s & ~%s', 'crorc': '%s | ~%s'}
        if m in cr_logic:
            return '%s = %s' % (
                self.crbit_prose(ops[0][1]),
                cr_logic[m] % (self.crbit_prose(ops[1][1]), self.crbit_prose(ops[2][1])))

        base = m[:-1] if m.endswith('o') and m not in ('addo',) else m
        if m == 'addo':
            base = 'add'
        if base in ('subf', 'subfc'):
            return '%s = %s - %s' % (name(0), name(2), name(1))
        if base == 'subfe':
            return '%s = %s + ~%s + CA' % (name(0), name(2), name(1))
        if base == 'subfze':
            return '%s = ~%s + CA' % (name(0), name(1))
        if base == 'subfme':
            return '%s = ~%s + CA - 1' % (name(0), name(1))
        if m == 'subfic':
            return '%s = %s - %s' % (name(0), name(2), name(1))
        if base == 'adde':
            return '%s = %s + %s + CA' % (name(0), name(1), name(2))
        if base == 'addze':
            return '%s = %s + CA' % (name(0), name(1))
        if base == 'addme':
            return '%s = %s + CA - 1' % (name(0), name(1))
        if m == 'andc':
            return '%s = %s & ~%s' % (name(0), name(1), name(2))
        if m == 'orc':
            return '%s = %s | ~%s' % (name(0), name(1), name(2))
        if m == 'nor':
            return '%s = ~(%s | %s)' % (name(0), name(1), name(2))
        if m == 'nand':
            return '%s = ~(%s & %s)' % (name(0), name(1), name(2))
        if m == 'eqv':
            return '%s = ~(%s ^ %s)' % (name(0), name(1), name(2))
        if m == 'cntlzw':
            return '%s = number of leading zero bits in %s' % (name(0), name(1))
        if m == 'extsb':
            return '%s = sign-extended low byte of %s' % (name(0), name(1))
        if m == 'extsh':
            return '%s = sign-extended low word of %s' % (name(0), name(1))
        if m == 'mulhwu':
            return '%s = high 32 bits of %s * %s (unsigned)' % (name(0), name(1), name(2))
        if m == 'mulhw':
            return '%s = high 32 bits of %s * %s (signed)' % (name(0), name(1), name(2))
        if m in ('lmw', 'stmw'):
            first = ops[0][1]
            verb = 'load' if m == 'lmw' else 'store'
            return '%s r%d..r31' % (verb, first)
        if m == 'twi' and ops[0][1] == 31:
            return 'unconditional trap'
        if m in ('bdnz', 'bdnzlr'):
            return 'CTR -= 1; branch while CTR != 0'
        if m == 'bdz':
            return 'CTR -= 1; branch when CTR == 0'
        return None

    # -- emission helpers --------------------------------------------------

    @staticmethod
    def with_comment(text, comment):
        if not comment:
            return text
        if len(text) < COMMENT_COL - 1:
            return text.ljust(COMMENT_COL - 1) + ' // ' + comment
        return text + '  // ' + comment

    def routine_fetches(self, addr):
        """True if the code at addr loads `data` from memory before it
        returns (used to tell fea_ routines from cea_ ones).  Follows
        unconditional branches and steps over calls."""
        loads = ('lbz', 'lhz', 'lha', 'lwz', 'lbzx', 'lhzx', 'lhax', 'lwzx',
                 'lbzu', 'lhzu', 'lhau', 'lwzu')
        for step in range(24):
            kind, value = self.kind.get(addr, ('long', 0))
            if kind != 'insn':
                return False
            if value.mnem in loads and value.ops[0] == ('r', 4):
                return True
            if value.mnem in ('blr', 'bctr'):
                return False
            if value.mnem == 'b':
                addr = value.ops[0][1]
                if addr >= TABLE_START:
                    return False
                continue
            addr += 4
        return False

    def uses_rtn_addr(self, addr):
        """True if the routine at addr starts by moving rtn_addr to LR/CTR."""
        for step in range(3):
            kind, value = self.kind.get(addr + 4 * step, ('long', 0))
            if kind != 'insn':
                return False
            if value.mnem in ('mtlr', 'mtctr') and value.ops[0] == ('r', 5):
                return True
        return False

    @staticmethod
    def _forms(opcodes, limit=6):
        counts = collections.Counter()
        for opcode in opcodes:
            counts[generalise(m68k.text(opcode))] += 1
        forms = [form for form, _ in counts.most_common()]
        lines = ['//     ' + form for form in forms[:limit]]
        if len(forms) > limit:
            lines.append('//     ... and %d more forms' % (len(forms) - limit))
        return lines

    def handler_summary(self, addr):
        """Block comment lines listing the 68K instructions that use the
        routine at addr."""
        if addr >= TABLE_START:
            return []
        lines = []
        users = self.table_users.get(addr)
        if users:
            lines.append('// Reached from %d dispatch table %s:' % (
                len(users), 'entry' if len(users) == 1 else 'entries'))
            lines += self._forms(users)
        users = self.continuation_users.get(addr)
        if users:
            lines.append('// Continuation (via rtn_addr) of %d dispatch table %s:' % (
                len(users), 'entry' if len(users) == 1 else 'entries'))
            lines += self._forms(users)
        users = self.emitter_users.get(addr)
        if users:
            lines.append('// Code generator for %d %s:' % (
                len(users), 'opcode' if len(users) == 1 else 'opcodes'))
            lines += self._forms(users)
            lines += self.emitter_examples.get(addr, [])
        users = self.decoder_users.get(addr)
        if users and addr in self.labels and not AUTO_LABEL.fullmatch(self.labels[addr]):
            lines.append('// The first pass comes here for %d %s:' % (
                len(users), 'opcode' if len(users) == 1 else 'opcodes'))
            lines += self._forms(users)
        return lines

    def label_lines(self, addr, out):
        """Emit the block comment and label(s) that belong above addr."""
        summary = self.handler_summary(addr)
        block = self.ann.blocks.get(addr, [])
        named = addr in self.labels and not AUTO_LABEL.fullmatch(self.labels[addr])
        if (block or summary or named or addr in EXTRA_LABELS) and out and out[-1] != '':
            out.append('')
        for line in block:
            out.append(('// ' + line).rstrip())
        if block and summary:
            out.append('//')
        out.extend(summary)
        for name in EXTRA_LABELS.get(addr, []):
            out.append(name + ':')
        if addr in self.labels:
            out.append(self.labels[addr] + ':')

    def emit_long(self, addr, out):
        self.label_lines(addr, out)
        text = ' ' * MNEM_COL + '.long'.ljust(OPND_COL - MNEM_COL) + '0x%08X' % self.words[addr // 4]
        out.append(self.with_comment(text, self.ann.eols.get(addr)))

    def emit_insn(self, addr, insn, out):
        self.label_lines(addr, out)
        comment = self.ann.eols.get(addr) or self.auto_comment(addr, insn)
        out.append(self.with_comment(self.instruction_text(addr, insn), comment))

    # -- data --------------------------------------------------------------

    def emit_data(self, start, end, kind, out):
        directive = lambda name, body: ' ' * MNEM_COL + name.ljust(OPND_COL - MNEM_COL) + body
        self.label_lines(start, out)
        image = self.image
        if kind == 'long':
            for addr in range(start, end, 4):
                if addr != start:
                    self.label_lines(addr, out)
                out.append(self.with_comment(
                    directive('.long', '0x%08X' % struct.unpack('>I', image[addr:addr + 4])[0]),
                    self.ann.eols.get(addr)))
        elif kind == 'short':
            for addr in range(start, end, 2):
                if addr != start:
                    self.label_lines(addr, out)
                out.append(self.with_comment(
                    directive('.short', '0x%04X' % struct.unpack('>H', image[addr:addr + 2])[0]),
                    self.ann.eols.get(addr)))
        elif kind in ('offs16', 'offs16e'):
            base, base_name = (drmap.DR_EMITTERS, 'dr_emitters') if kind == 'offs16e' else (0, 'cb')
            for addr in range(start, end, 2):
                if addr != start:
                    self.label_lines(addr, out)
                value = struct.unpack('>H', image[addr:addr + 2])[0]
                body = '%s - %s' % (self.labels[base + value], base_name) if value else '0'
                out.append(self.with_comment(directive('.short', body), self.ann.eols.get(addr)))
        elif kind in ('seq8', 'seq16'):
            for addr in range(start, end, 4):
                if addr != start:
                    self.label_lines(addr, out)
                offset, rest = struct.unpack('>HH', image[addr:addr + 4])
                first = '%s - dr_emitters - 4' % self.labels[drmap.DR_EMITTERS + offset + 4] \
                    if offset else '0'
                condition = m68k.CC[(addr - start) // 4 % 16]
                if kind == 'seq8':
                    second = directive('.byte', '%d, 0x%02X' % (rest >> 8, rest & 0xFF))
                else:
                    second = directive('.short', '%d' % rest)
                out.append(self.with_comment(directive('.short', first),
                                             self.ann.eols.get(addr) or condition))
                out.append(second)
        elif kind == 'byte':
            addr = start
            while addr < end:
                stop = min(addr + 8, end)
                for inner in range(addr + 1, stop):
                    if inner in self.labels or inner in self.ann.eols:
                        stop = inner
                        break
                if addr != start:
                    self.label_lines(addr, out)
                body = ', '.join('0x%02X' % b for b in image[addr:stop])
                out.append(self.with_comment(directive('.byte', body), self.ann.eols.get(addr)))
                addr = stop
        elif kind == 'ascii':
            raw = image[start:end]
            text = raw.rstrip(b'\0')
            padding = len(raw) - len(text)
            out.append(directive('.ascii', '"%s"' % text.decode('ascii').replace('"', '\\"')))
            if padding:
                out.append(directive('.space', '%d' % padding))
        elif kind == 'zero':
            if any(image[start:end]):
                fail('zero range %05X-%05X is not all zero' % (start, end))
            out.append(self.with_comment(directive('.space', '0x%X' % (end - start)),
                                         self.ann.eols.get(start)))
        else:
            fail('unknown data kind %s at %05X' % (kind, start))

    # -- code regions ------------------------------------------------------

    def is_nop(self, addr):
        return self.words[addr // 4] == 0x60000000 and self.kind[addr][0] == 'insn'

    def emit_code(self, start, end, out):
        addr = start
        while addr < end:
            data = self.data_at.get(addr)
            if data:
                self.emit_data(data[0], data[1], data[2], out)
                addr = (data[1] + 3) & ~3
                continue
            kind, value = self.kind[addr]
            if kind == 'data':
                fail('offset %05X is inside a data range but not at its start' % addr)
            if kind == 'long':
                self.emit_long(addr, out)
                addr += 4
                continue
            if self.is_nop(addr) and addr not in self.ann.eols:
                run_end = addr + 4
                while (run_end < end and self.is_nop(run_end)
                       and run_end not in self.labels and run_end not in self.ann.eols
                       and run_end not in self.ann.blocks and run_end not in self.data_at):
                    run_end += 4
                boundary = (run_end >= end or run_end in self.labels
                            or run_end in self.data_at or run_end in self.ann.blocks)
                align = self.ann.aligns.get(addr) or (pick_align(addr, run_end) if boundary else None)
                if align and (addr + align - 1) // align * align == run_end and addr % align:
                    self.label_lines(addr, out)
                    out.append(' ' * MNEM_COL + 'ALIGN(%s)' % (
                        align if align < 1024 else '0x%X' % align))
                    addr = run_end
                    continue
            self.emit_insn(addr, value, out)
            addr += 4

    # -- instruction pair tables ------------------------------------------

    def emit_pairs(self, start, end, out, describe):
        """Emit a table of two-instruction entries.  `describe(index)` gives
        the comment for entry `index` (or None)."""
        for addr in range(start, end, 8):
            index = (addr - start) // 8
            comment = describe(index)
            for offset in (0, 4):
                here = addr + offset
                if here in self.ann.blocks or here in EXTRA_LABELS:
                    if out and out[-1] != '':
                        out.append('')
                    for line in self.ann.blocks.get(here, []):
                        out.append(('// ' + line).rstrip())
                for name in EXTRA_LABELS.get(here, []):
                    out.append(name + ':')
                if here in self.labels:
                    out.append(self.labels[here] + ':')
                kind, value = self.kind[here]
                note = self.ann.eols.get(here) or (comment if offset == 0 else None)
                if kind == 'insn':
                    out.append(self.with_comment(self.instruction_text(here, value), note))
                else:
                    text = ' ' * MNEM_COL + '.long'.ljust(OPND_COL - MNEM_COL) + '0x%08X' % self.words[here // 4]
                    out.append(self.with_comment(text, note))

    def emit_optable(self, start, end, out):
        first = (start - TABLE_START) // 8

        def describe(index):
            opcode = first + index
            return '%04X  %s' % (opcode, m68k.text(opcode))

        for addr in range(start, end, 0x40 * 8):
            opcode = (addr - TABLE_START) // 8
            out.append('')
            out.append('// ---- $%04X-$%04X ' % (opcode, opcode + 0x3F) + '-' * 56)
            self.emit_pairs(addr, min(addr + 0x40 * 8, end), out,
                            lambda index, base=opcode - first: describe(base + index))

    # -- driver ------------------------------------------------------------

    def generate(self):
        self.analyse()
        layout = self.ann.layout
        written = []
        for position, (start, path, kind) in enumerate(layout):
            end = layout[position + 1][0] if position + 1 < len(layout) else IMAGE_SIZE
            out = []
            if kind == 'code':
                self.emit_code(start, end, out)
            elif kind == 'optable':
                self.emit_optable(start, end, out)
            elif kind == 'pairs':
                self.emit_pairs(start, end, out, lambda index: None)
            else:
                fail('unknown layout kind %s' % kind)
            header = ['// %s - offsets %05X-%05X' % (os.path.basename(path), start, end - 1),
                      '//'] + GENERATED_BANNER.rstrip('\n').split('\n') + ['']
            while out and out[0] == '':
                out.pop(0)
            written.append(path)
            if path in self.ann.frozen:
                continue                        # hand-maintained from now on
            self.write(path, '\n'.join(header + out) + '\n')
        self.write_top(written)
        return written

    def write_top(self, files):
        lines = [
            '// Emulator.S - Apple 68LC040 emulator for PowerPC, top level',
            '//',
            '// Assembling this file reproduces the .text section of Emulator.x.',
            '//'] + GENERATED_BANNER.rstrip('\n').split('\n') + [
            '',
            '#include "include/Registers.inc"',
            '#include "include/EmulatorState.inc"',
            '#include "include/Macros.inc"',
            '',
            '// EmTop, EmEntry, EmKernelTrapTable, EmBtm, OpcodeTblTop and OpcodeTblBtm',
            '// are the symbols exported by Emulator.x.  They are deliberately not',
            '// declared .globl: a branch to a global symbol would need a relocation,',
            '// and this image must assemble with none.  tools/elf2xcoff.py picks',
            '// them up from the local symbol table.',
            '',
            '        .text',
            '']
        for path in files:
            lines.append('#include "%s"' % path)
        lines += ['', 'OpcodeTblBtm:', '']
        self.write('Emulator.S', '\n'.join(lines))

    @staticmethod
    def write(path, text):
        full = os.path.join(ROOT, 'src', path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        old = None
        if os.path.exists(full):
            with open(full, encoding='utf-8') as handle:
                old = handle.read()
        if old != text:
            with open(full, 'w', encoding='utf-8') as handle:
                handle.write(text)

    def report(self):
        code = {a: n for a, n in self.labels.items() if a < TABLE_START}
        auto = sum(1 for n in code.values() if re.fullmatch(r'[LD]_[0-9A-F]{5}', n))
        templates = sum(1 for n in code.values() if re.fullmatch(r'T_[0-9A-F]{5}', n))
        local = sum(1 for n in code.values() if re.fullmatch(r'.*_L[0-9]+', n))
        manual = sum(1 for a in self.ann.labels if a < TABLE_START)
        named = len(code) - auto - local - manual - templates
        longs = sum(1 for a, (k, _) in self.kind.items() if k == 'long' and a < TABLE_START)
        print('labels below the table: %d hand-named, %d named from the dispatch '
              'table, %d local to a named routine, %d address-only'
              % (manual, named, local, auto))
        print('recompiler templates labelled: %d' % templates)
        print('undecoded words emitted as .long: %d' % longs)


def main():
    generator = Generator()
    files = generator.generate()
    print('wrote %d source files' % (len(files) + 1))
    generator.report()


if __name__ == '__main__':
    main()
