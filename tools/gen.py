def mask32(mb, me):
    """PowerPC MASK(mb, me) with IBM bit numbering (bit 0 is the MSB)."""
    if mb <= me:
        return ((1 << (me - mb + 1)) - 1) << (31 - me)
    return 0xFFFFFFFF ^ (((1 << (mb - me - 1)) - 1) << (31 - mb + 1))


def bit_slice(hi, lo):
    return '[%d]' % hi if hi == lo else '[%d:%d]' % (hi, lo)


def pick_align(start, end):
    """Alignment whose padding from `start` reaches exactly `end`, or None."""
    pad = end - start
    for n in (64, 32, 16, 8):
        if end % n == 0 and pad < n:
            return n
    n = 128
    while n <= CODE_BLOCK:
        if end % n == 0 and pad < n:
            return n
        n *= 2
    return None


def generalise(text):
    """Replace specific register numbers and quick constants in a 68K
    instruction with placeholders so that families can be summarised."""
    text = re.sub(r'\bD[0-7]\b', 'Dn', text)
    text = re.sub(r'\bA[0-7]\b', 'An', text)
    text = re.sub(r'#\$[0-9A-F]{2}\b', '#<q>', text)
    text = re.sub(r'#[0-9]+\b', '#<q>', text)
    text = re.sub(r'\$A[0-9A-F]{3}', '$Axxx', text)
    return re.sub(r'\s+', ' ', text)


